export function getProductBySlug(slug: string): Product | undefined {
  return products.find((p) => p.slug === slug);
}

export function getProductsByCategory(category: string): Product[] {
  return products.filter((p) => p.category === category);
}

export function getProductsByTheme(theme: string): Product[] {
  return products.filter((p) => p.theme === theme);
}

export function getTrending(): Product[] {
  return products.filter((p) => p.trending);
}

export function getJustAdded(): Product[] {
  return products.filter((p) => p.justAdded);
}

export function getShipReady(): Product[] {
  return products.filter((p) => p.shipReady);
}

export function getExclusives(): Product[] {
  return products.filter((p) => p.exclusive);
}

export function getPreOrders(): Product[] {
  return products.filter((p) => p.status === "pre-order");
}

export function getDeals(): Product[] {
  return products.filter((p) => p.compareAt && p.compareAt > p.price);
}

export function searchProducts(q: string): Product[] {
  const term = q.toLowerCase().trim();
  if (!term) return products;
  return products.filter(
    (p) =>
      p.name.toLowerCase().includes(term) ||
      p.brand.toLowerCase().includes(term) ||
      p.theme.toLowerCase().includes(term) ||
      p.category.toLowerCase().includes(term) ||
      p.sku.toLowerCase().includes(term),
  );
}

export function getCategory(slug: string): Category | undefined {
  return categories.find((c) => c.slug === slug);
}

export function getTheme(slug: string): Theme | undefined {
  return themes.find((t) => t.slug === slug);
}

